/* стиль-строка как в Custom Mode: жанр, настроение и bpm можно написать словами */
function parseStyle(text){
  const t=(text||'').toLowerCase();
  let style=null,mood=null,bpm=0;
  for(const k of GENRE_KEYS){if(KW[k].some(w=>t.includes(w))){style=k;break;}}
  for(const m in MOOD_KW){if(MOOD_KW[m].some(w=>t.includes(w))){mood=m;break;}}
  const bm=t.match(/(\d{2,3})\s*(?:bpm|уд)/);
  if(bm){const v=+bm[1];if(v>=50&&v<=200)bpm=v;}
  return {style,mood,bpm};
}
/* свой текст с тегами [Куплет]/[Verse], [Припев]/[Chorus] и т.д. */
function parseCustomLyrics(text){
  if(!text||!text.trim())return null;
  const TAGMAP={'интро':'Интро','intro':'Интро','куплет':'Куплет','verse':'Куплет','припев':'Припев','chorus':'Припев','хук':'Припев','hook':'Припев','бридж':'Бридж','bridge':'Бридж','аутро':'Аутро','outro':'Аутро','пре-припев':'Бридж','пред-припев':'Бридж','pre-chorus':'Бридж','prechorus':'Бридж','инструментал':'Инструментал','instrumental':'Инструментал','брейк':'Инструментал','break':'Инструментал'};
  const KIND={'Интро':'intro','Куплет':'verse','Припев':'chorus','Бридж':'bridge','Аутро':'outro','Инструментал':'intro'};
  const out=[];let cur=null;let verseNum=0;
  String(text).split(/\r?\n/).forEach(l=>{
    const s=l.trim();
    const m=s.match(/^\[(.+?)\]$/);
    if(m){
      const tagRaw=m[1].toLowerCase().trim();
      const tag=tagRaw.replace(/\s+\d+$/,'');
      const base=TAGMAP[tag];
      if(base){
        let name=base;
        if(base==='Куплет'){verseNum++;name='Куплет '+verseNum;}
        cur={sec:name,kind:KIND[base],lines:[]};
        out.push(cur);return;
      }
    }
    if(!s)return;
    if(cur)cur.lines.push(s);
  });
  const clean=out.filter(s=>s.lines.length);
  if(clean.length)return clean;
  const lines=String(text).split(/\r?\n/).map(x=>x.trim()).filter(x=>x);
  return lines.length?[{sec:'Куплет 1',kind:'verse',lines}]:null;
}
function bindLyricsTimings(lyrics,plan){
  if(!lyrics)return;
  const kindFor={'Припев':'chorus','Куплет 1':'verse','Куплет 2':'verse','Бридж':'bridge','Интро':'intro','Аутро':'outro','Инструментал':'intro'};
  const counts={chorus:0,verse:0};
  lyrics.forEach(s=>{
    const kind=s.kind||kindFor[s.sec]||'chorus';
    s.kind=kind;
    let t0=0;
    if(kind==='chorus'){const cs=plan.sections.filter(x=>x.kind==='chorus');const c=cs[Math.min(counts.chorus,cs.length-1)];t0=c?c.start:0;counts.chorus++;}
    else if(kind==='verse'){const vs=plan.sections.filter(x=>x.kind==='verse');const v=vs[Math.min(counts.verse,vs.length-1)];t0=v?v.start:0;counts.verse++;}
    else if(kind==='bridge'){const bs=plan.sections.filter(x=>x.kind==='bridge');t0=bs[0]?bs[0].start:0;}
    else if(kind==='outro'){const os=plan.sections.filter(x=>x.kind==='outro');t0=os[0]?os[0].start:0;}
    else{t0=plan.sections[0]?plan.sections[0].start:0;}
    s.t0=t0;
  });
  lyrics.forEach((s,i)=>{s.t1=(i<lyrics.length-1&&lyrics[i+1].t0!=null)?lyrics[i+1].t0:plan.duration;});
}

